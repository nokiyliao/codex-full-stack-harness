function isAuthorityMessage(item) {
  return item?.type === "message" && (item.role === "developer" || item.role === "system");
}

function isToolCall(item) {
  return item?.type === "function_call" || item?.type === "custom_tool_call";
}

function isToolOutput(item) {
  return item?.type === "function_call_output" || item?.type === "custom_tool_call_output";
}

function latestUniqueAuthorityMessages(input) {
  const seen = new Set();
  const selected = [];
  for (let index = input.length - 1; index >= 0; index -= 1) {
    const item = input[index];
    if (!isAuthorityMessage(item)) continue;
    const key = JSON.stringify(item);
    if (seen.has(key)) continue;
    seen.add(key);
    selected.unshift(item);
  }
  return selected;
}

function recentAtomicTailStart(input, minimumStart, targetBytes) {
  let start = input.length;
  let bytes = 2;
  while (start > minimumStart) {
    const itemBytes = Buffer.byteLength(JSON.stringify(input[start - 1])) + 1;
    if (start < input.length && bytes + itemBytes > targetBytes) break;
    start -= 1;
    bytes += itemBytes;
  }

  let changed = true;
  while (changed) {
    changed = false;
    const selectedCallIds = new Set(input.slice(start)
      .filter((item) => (isToolCall(item) || isToolOutput(item)) && item.call_id)
      .map((item) => item.call_id));
    for (const callId of selectedCallIds) {
      let pairStart = start;
      for (let index = minimumStart; index < start; index += 1) {
        const item = input[index];
        if ((isToolCall(item) || isToolOutput(item)) && item.call_id === callId) {
          pairStart = Math.min(pairStart, index);
        }
      }
      if (pairStart < start) {
        start = pairStart;
        changed = true;
        break;
      }
    }
  }
  return start;
}

function clipString(text, maxChars) {
  const marker = "\n[switchboard_truncated]";
  if (text.length <= maxChars) return text;
  const budget = Math.max(0, maxChars - marker.length);
  const head = Math.ceil(budget * 0.75);
  const tail = budget - head;
  return `${text.slice(0, head)}${marker}${tail > 0 ? text.slice(text.length - tail) : ""}`;
}

function clipEvidence(value, maxChars) {
  if (typeof value === "string") return clipString(value, maxChars);
  if (Array.isArray(value)) {
    return value.map((part) => {
      if (!part || typeof part !== "object") return part;
      const key = ["text", "input_text", "output_text"].find((name) => typeof part[name] === "string");
      if (!key || part[key].length <= maxChars) return part;
      return { ...part, [key]: clipString(part[key], maxChars) };
    });
  }
  if (value && typeof value === "object") {
    const json = JSON.stringify(value);
    return json.length <= maxChars ? value : clipString(json, maxChars);
  }
  return value;
}

// A long Codex tool turn can make the mandatory tail larger than xAI's
// history budget after compaction. Keep the current user request and clip
// the largest tool evidence until the tail fits.
function historyTooLarge(input, maxBytes) {
  try {
    boundExternalHistory(input, maxBytes);
    return false;
  } catch (error) {
    return error?.code === "EXTERNAL_MANDATORY_CONTEXT_TOO_LARGE";
  }
}

function inputThatFits(input, maxBytes) {
  const items = Array.isArray(input) ? input : [];
  if (!historyTooLarge(items, maxBytes)) return items;
  const copy = structuredClone(items);
  const lastUser = copy.findLastIndex((item) => item?.type === "message" && item.role === "user");
  for (let pass = 0; pass < 8 && historyTooLarge(copy, maxBytes); pass += 1) {
    const ranked = copy
      .map((item, index) => ({ index, bytes: Buffer.byteLength(JSON.stringify(item)) }))
      .filter(({ index, bytes }) => index !== lastUser && bytes > 512)
      .filter(({ index }) => {
        const item = copy[index];
        return isToolOutput(item) || isToolCall(item);
      })
      .sort((left, right) => right.bytes - left.bytes);
    let changed = false;
    for (const { index, bytes } of ranked) {
      const item = copy[index];
      const limit = Math.max(256, Math.floor(bytes / 2));
      if (isToolOutput(item) && item.output != null) {
        const next = clipEvidence(item.output, limit);
        if (JSON.stringify(next) !== JSON.stringify(item.output)) {
          item.output = next;
          changed = true;
        }
      } else if (isToolCall(item) && typeof item.arguments === "string" && item.arguments.length > limit) {
        item.arguments = clipString(item.arguments, limit);
        changed = true;
      }
      if (!historyTooLarge(copy, maxBytes)) break;
    }
    if (!changed) break;
  }
  if (historyTooLarge(copy, maxBytes)) boundExternalHistory(copy, maxBytes);
  return copy;
}

function providerReadyCompactedInput(items) {
  const bounded = boundExternalHistory(
    inputThatFits(items, DEFAULT_MAX_EXTERNAL_HISTORY_BYTES),
    DEFAULT_MAX_EXTERNAL_HISTORY_BYTES,
  );
  return bounded.map((item) => {
    if (item?.type !== "compaction") return item;
    const { [trustedProviderStateMarker]: _trusted, ...providerItem } = item;
    return providerItem;
  });
}

function rejectionLocation(errorText, bodyJson, body) {
  const columns = [...String(errorText || "").matchAll(/at line 1 column (\d+)/g)]
    .map((match) => Number(match[1]))
    .filter(Number.isFinite);
  const column = columns.at(-1);
  if (!column || !body || typeof body !== "object") return null;

  const offset = column - 1;
  let propertyCursor = 1;
  for (const [key, value] of Object.entries(body)) {
    const propertyPrefix = `${JSON.stringify(key)}:`;
    const propertyStart = bodyJson.indexOf(propertyPrefix, propertyCursor);
    if (propertyStart < 0) continue;
    const valueStart = propertyStart + propertyPrefix.length;
    const valueStartBytes = Buffer.byteLength(bodyJson.slice(0, valueStart));
    const propertyEnd = valueStartBytes + Buffer.byteLength(JSON.stringify(value));
    if (offset <= propertyEnd) {
      if (key !== "input" || !Array.isArray(value)) {
        return { column, key, index: null, type: "top_level", keys: [] };
      }
      break;
    }
    propertyCursor = propertyStart + propertyPrefix.length + JSON.stringify(value).length + 1;
  }
  if (!Array.isArray(body.input)) return { column, key: "unknown", index: null, type: "top_level", keys: [] };

  const marker = '"input":[';
  const markerIndex = bodyJson.indexOf(marker);
  if (markerIndex < 0) return null;
  let cursor = Buffer.byteLength(bodyJson.slice(0, markerIndex + marker.length));
  for (let index = 0; index < body.input.length; index += 1) {
    const item = body.input[index];
    const serialized = JSON.stringify(item);
    const end = cursor + Buffer.byteLength(serialized);
    if (offset <= end) {
      return {
        column,
        index,
        type: typeof item?.type === "string" ? item.type : "message_shorthand",
        keys: item && typeof item === "object" ? Object.keys(item).sort().slice(0, 12) : [],
      };
    }
    cursor = end + 1;
  }
  return { column, key: "unknown", index: null, type: "top_level", keys: [] };
}

function inputShapeCode(input) {
  const counts = new Map();
  const openCalls = new Set();
  const seenCalls = new Set();
  let orphanOutputs = 0;
  let duplicateCalls = 0;
  let images = 0;
  for (const item of Array.isArray(input) ? input : []) {
    const type = typeof item?.type === "string" ? item.type : "message_shorthand";
    counts.set(type, (counts.get(type) || 0) + 1);
    if (type === "function_call") {
      if (seenCalls.has(item.call_id)) duplicateCalls += 1;
      seenCalls.add(item.call_id);
      openCalls.add(item.call_id);
    } else if (type === "function_call_output") {
      if (!openCalls.delete(item.call_id)) orphanOutputs += 1;
    } else if (type === "message") {
      images += (Array.isArray(item.content) ? item.content : [])
        .filter((part) => part?.type === "input_image").length;
    }
  }
  const typeCounts = [...counts.entries()]
    .map(([type, count]) => `${type.replace(/[^A-Za-z0-9]+/g, "_").toUpperCase()}${count}`)
    .join("_");
  return `N${Array.isArray(input) ? input.length : 0}_${typeCounts}_ORPHAN${orphanOutputs}_DUP${duplicateCalls}_OPEN${openCalls.size}_IMG${images}`;
}

function rejectedRequestError(path, status, errorText, bodyJson, body) {
  const location = rejectionLocation(errorText, bodyJson, body);
  const topLevelShape = Object.keys(body || {})
    .map((key) => key.toUpperCase().replace(/[^A-Z0-9]+/g, "_"))
    .join("_")
    .slice(0, 220);
  const inputShape = inputShapeCode(body?.input);
  const locationCode = location
    ? location.type === "top_level"
      ? `XAI_REQUEST_SCHEMA_REJECTED_${String(location.key).toUpperCase().replace(/[^A-Z0-9]+/g, "_")}`
        + (location.key === "unknown"
          ? `_C${location.column}_B${Buffer.byteLength(bodyJson)}_K_${topLevelShape}`
            + `_S_${inputShape}`
          : "")
      : `XAI_INPUT_SCHEMA_REJECTED_I${location.index ?? "X"}_${location.type.toUpperCase().replace(/[^A-Z0-9]+/g, "_")}`
    : "XAI_UPSTREAM_REJECTED";
  const structuralDetail = location
    ? location.type === "top_level"
      ? ` top-level key=${location.key} column=${location.column}`
      : ` input[${location.index ?? "?"}] type=${location.type} keys=${location.keys.join(",")} column=${location.column}`
    : "";
  return Object.assign(new Error(`xAI ${path} rejected the request schema.${structuralDetail}`), {
    code: locationCode,
    status,
  });
}

async function compactLargeInput(clean, signal) {
  const input = Array.isArray(clean.input) ? clean.input : [];
  if (AUTO_COMPACT_THRESHOLD_BYTES <= 0 || clean.previous_response_id || input.length < 2) {
    return { clean, compacted: false };
  }
  const activeTurnIndex = lastUserMessageIndex(input);
  if (activeTurnIndex < 0) return { clean, compacted: false };

  const compactAndRebind = async (prefix, tailStart, scope) => {
    const compacted = await postXai("/responses/compact", {
      model: clean.model,
      input: prefix,
      ...(clean.prompt_cache_key ? { prompt_cache_key: clean.prompt_cache_key } : {}),
    }, signal);
    if (!validCompactionOutput(compacted.output)) {
      throw Object.assign(new Error("xAI compaction returned no reusable compaction item"), {
        code: "XAI_COMPACT_INVALID",
      });
    }
    const trustedCompaction = compacted.output.map((item) => ({
      ...item,
      [trustedProviderStateMarker]: true,
    }));
    const activeTail = input.slice(tailStart).filter((item) => !isAuthorityMessage(item));
    const rebound = [
      ...trustedCompaction,
      ...latestUniqueAuthorityMessages(input),
      input[activeTurnIndex],
      ...activeTail,
    ];
    return {
      clean: { ...clean, input: providerReadyCompactedInput(rebound) },
      compacted: true,
      compaction_scope: scope,
    };
  };

  if (activeTurnIndex > 0) {
    const prefix = input.slice(0, activeTurnIndex);
    const prefixJson = JSON.stringify(prefix);
    const prefixBytes = Buffer.byteLength(prefixJson);
    if (prefixBytes >= AUTO_COMPACT_THRESHOLD_BYTES) {
      const compressionRatio = deflateRawSync(prefixJson).length / prefixBytes;
      if (compressionRatio >= AUTO_COMPACT_MIN_RATIO) {
        return compactAndRebind(prefix, activeTurnIndex + 1, "prior_turns");
      }
    }
  }

  try {
    return {
      clean: { ...clean, input: boundExternalHistory(input, DEFAULT_MAX_EXTERNAL_HISTORY_BYTES) },
      compacted: false,
    };
  } catch (error) {
    if (error?.code !== "EXTERNAL_MANDATORY_CONTEXT_TOO_LARGE") throw error;
  }

  const tailStart = recentAtomicTailStart(input, activeTurnIndex + 1, ACTIVE_TAIL_BYTES);
  if (tailStart <= activeTurnIndex + 1) {
    const fitted = inputThatFits(input, DEFAULT_MAX_EXTERNAL_HISTORY_BYTES);
    if (fitted !== input) {
      return {
        clean: { ...clean, input: providerReadyCompactedInput(fitted) },
        compacted: true,
        compaction_scope: "tool_evidence_shrunk",
      };
    }
    boundExternalHistory(input, DEFAULT_MAX_EXTERNAL_HISTORY_BYTES);
  }
  return compactAndRebind(input.slice(0, tailStart), tailStart, "active_turn");
}

function isProviderEchoItem(item) {
  return item?.type === "reasoning"
    || item?.type === "agent_message"
    || ((item?.type === "message") && item?.role === "assistant")
    || ["function_call", "custom_tool_call", "tool_search_call"].includes(item?.type);
}

function xaiCallerDigests(input) {
  return (Array.isArray(input) ? input : [])
    .filter((item) => !isProviderEchoItem(item))
    .map((item) => createHash("sha256").update(JSON.stringify(item)).digest("hex"));
}

function shouldPersistXaiSession(key) {
  return typeof key === "string"
    && key.startsWith("thread-")
    && (Boolean(process.env.SWITCHBOARD_XAI_SESSION_DIR)
      || !RESPONSES_URL.startsWith("ws://127.0.0.1:"));
}

function xaiSessionStatePath(key) {
  const safeKey = String(key || "")
    .replace(/[^A-Za-z0-9_-]/g, "_")
    .slice(0, 96);
  const digest = createHash("sha256").update(String(key || "")).digest("hex").slice(0, 16);
  return path.join(SESSION_STATE_DIR, `${safeKey}-${digest}.json`);
}

function loadPersistedXaiSession(key) {
  if (!shouldPersistXaiSession(key)) return null;
  const target = xaiSessionStatePath(key);
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(target, "utf8"));
  } catch {
    return null;
  }
  const expired = !(Number(parsed?.lastUsedAt) > 0)
    || (Date.now() - Number(parsed.lastUsedAt) > SESSION_STATE_TTL_MS);
  if (expired || parsed?.version !== 1 || parsed.key !== key) {
    try { rmSync(target, { force: true }); } catch {}
    return null;
  }
  return parsed;
}

function savePersistedXaiSession(session) {
  if (!shouldPersistXaiSession(session.key)) return;
  try {
    mkdirSync(SESSION_STATE_DIR, { recursive: true, mode: 0o700 });
    const target = xaiSessionStatePath(session.key);
    const temp = `${target}.${process.pid}.${randomUUID()}.tmp`;
    const payload = {
      version: 1,
      key: session.key,
      lastUsedAt: session.lastUsedAt,
      responseIds: [...session.responseIds],
      priorCallerDigests: session.priorCallerDigests,
      prefix: session.prefix,
    };
    writeFileSync(temp, JSON.stringify(payload), { mode: 0o600 });
    renameSync(temp, target);
  } catch {
    // Session state persistence is an optimization; never fail an active turn.
  }
}

function removePersistedXaiSession(key) {
  if (!shouldPersistXaiSession(key)) return;
  try {
    rmSync(xaiSessionStatePath(key), { force: true });
  } catch {}
}

class XaiSession {
  constructor(key) {
    this.key = key;
    this.socket = null;
    this.openedAt = 0;
    const restored = loadPersistedXaiSession(key);
    this.lastUsedAt = restored ? Number(restored.lastUsedAt) : Date.now();
    this.queue = Promise.resolve();
    this.responseIds = new Set(Array.isArray(restored?.responseIds) ? restored.responseIds : []);
    this.compactedContinuations = new Map();
    this.priorCallerDigests = Array.isArray(restored?.priorCallerDigests) ? restored.priorCallerDigests : null;
    this.prefix = restored?.prefix && typeof restored.prefix === "object" ? restored.prefix : null;
    // The session key is the caller's thread (switchboard externalThreadSessionKey)
    // when it named one, so the provider cache follows the thread across
    // reconnects and requests. Only this digest reaches xAI.
    this.cacheKey = createHash("sha256").update(`xai-prompt-cache:${key}`).digest("hex");
  }

  canContinue(input) {
    if (!Array.isArray(this.priorCallerDigests) || this.priorCallerDigests.length === 0) return false;
    const current = xaiCallerDigests(input);
    if (current.length <= this.priorCallerDigests.length) return false;
    return this.priorCallerDigests.every((digest, index) => current[index] === digest);
  }

  async connect(forceTokenRefresh = false) {
    if (this.socket?.readyState === WebSocket.OPEN) return this.socket;
    const bearer = await token(forceTokenRefresh);
    this.socket = await new Promise((resolve, reject) => {
      const socket = new WebSocket(RESPONSES_URL, {
        headers: { authorization: `Bearer ${bearer}` },
        perMessageDeflate: true,
        handshakeTimeout: OPEN_TIMEOUT_MS,
        maxPayload: 96 * 1024 * 1024,
      });
      const timer = setTimeout(() => {
        socket.terminate();
        reject(Object.assign(new Error("xAI WebSocket open timeout"), { code: "XAI_TIMEOUT" }));
      }, OPEN_TIMEOUT_MS);
      socket.once("open", () => {
        clearTimeout(timer);
        this.openedAt = Date.now();
        resolve(socket);
      });
      socket.once("unexpected-response", (_request, response) => {
        clearTimeout(timer);
        const error = Object.assign(new Error(`xAI WebSocket handshake returned ${response.statusCode}`), {
          code: response.statusCode === 401 ? "XAI_AUTH_REJECTED" : "XAI_UPSTREAM_REJECTED",
          status: response.statusCode,
        });
        reject(error);
      });
      socket.once("error", (error) => {
        clearTimeout(timer);
        reject(Object.assign(new Error("xAI WebSocket connection failed"), { code: error.code || "XAI_CONNECT_FAILED" }));
      });
      socket.once("close", () => {
        if (this.socket === socket) this.socket = null;
      });
    });
    return this.socket;
  }

  exchange(socket, frame, bridge, emit, signal) {
    return new Promise((resolve, reject) => {
      if (signal?.aborted) {
        reject(cancelledError());
        return;
      }
      let finished = false;
      const outputItems = [];
      const requestJson = JSON.stringify(frame);
      const requestBytes = Buffer.byteLength(requestJson);
      const timer = setTimeout(() => {
        finish(() => {
          socket.terminate();
          reject(Object.assign(new Error("xAI response timeout"), { code: "XAI_TIMEOUT" }));
        });
      }, REQUEST_TIMEOUT_MS);
      const cleanup = () => {
        clearTimeout(timer);
        socket.off("message", onMessage);
        socket.off("close", onClose);
        socket.off("error", onError);
        signal?.removeEventListener("abort", onAbort);
      };
      const finish = (callback) => {
        if (finished) return;
        finished = true;
        cleanup();
        callback();
      };
      const onMessage = (data, isBinary) => {
        if (isBinary) {
          finish(() => reject(Object.assign(new Error("xAI returned a binary Responses frame"), { code: "XAI_INVALID_FRAME" })));
          return;
        }
        let event;
        let providerEvent;
        try {
          providerEvent = JSON.parse(data.toString());
          event = restoreEvent(providerEvent, bridge);
        } catch {
          finish(() => reject(Object.assign(new Error("xAI returned invalid Responses JSON"), { code: "XAI_INVALID_EVENT" })));
          return;
        }
        if (event?.type === "error" && event?.error?.code === "previous_response_not_found") {
          finish(() => reject(Object.assign(new Error("xAI previous response state is unavailable"), {
            code: "previous_response_not_found",
            status: event.status || 409,
          })));
          return;
        }
        if (providerEvent?.type === "response.output_item.done" && providerEvent.item) outputItems.push(providerEvent.item);
        emit(event);
        if (terminalEvent(event)) finish(() => resolve({
          ...event,
          switchboard_output_items: outputItems,
          switchboard_request_bytes: requestBytes,
        }));
      };
      const onClose = () => finish(() => reject(Object.assign(new Error("xAI WebSocket closed before completion"), { code: "XAI_EARLY_EOF" })));
      const onError = () => finish(() => reject(Object.assign(new Error("xAI WebSocket request failed"), { code: "XAI_STREAM_ERROR" })));
      const onAbort = () => finish(() => {
        if (socket.readyState === WebSocket.OPEN) {
          socket.send(JSON.stringify({ type: "response.cancel" }), () => socket.terminate());
        } else {
          socket.terminate();
        }
        reject(cancelledError());
      });
      socket.on("message", onMessage);
      socket.on("close", onClose);
      socket.on("error", onError);
      signal?.addEventListener("abort", onAbort, { once: true });
      if (signal?.aborted) onAbort();
      if (finished) return;
      socket.send(requestJson, (error) => {
        if (error) finish(() => reject(Object.assign(new Error("xAI WebSocket send failed"), { code: "XAI_SEND_FAILED" })));
      });
    });
  }

  run(body, emit, signal) {
    const operation = async () => {
      if (signal?.aborted) throw cancelledError();
      if (body?.previous_response_id) {
        if (!this.responseIds.has(body.previous_response_id)) throw Object.assign(new Error("xAI continuation state is not owned by this session"), {
          code: "previous_response_not_found",
          status: 409,
        });
      }
      this.lastUsedAt = Date.now();
      const ownedContinuation = Boolean(body.previous_response_id)
        && this.responseIds.has(body.previous_response_id);
      const threadContinuation = ownedContinuation || this.canContinue(body.input);
      const toolQuarantine = loadToolQuarantine();
      const preparationOptions = {
        toolQuarantine,
        allowProviderContinuation: Boolean(body.previous_response_id),
        maxHistoryBytes: !body.previous_response_id && AUTO_COMPACT_THRESHOLD_BYTES > 0
          ? PRECOMPACTION_HISTORY_BYTES
          : DEFAULT_MAX_EXTERNAL_HISTORY_BYTES,
      };
      // Every turn keeps its history, guidance and tools; questions about the
      // route are answered from the route identity block in the instructions.
      let requestBody = body;
      if (Array.isArray(body.input) && body.input.length > 0 && body.generate !== false) {
        const fitted = inputThatFits(body.input, preparationOptions.maxHistoryBytes);
        if (fitted !== body.input) requestBody = { ...body, input: fitted };
      }
      const available = externalAvailableIdentities(requestBody, toolQuarantine);
      // A follow-up often omits tools discovered on the first turn. Keep the
      // frozen list when every advertised tool is unchanged. A new or edited
      // tool still rebuilds the prefix.
      const retainFrozen = threadContinuation
        && this.prefix
        && body.tool_choice !== "none"
        && Array.isArray(this.prefix.definitions)
        && catalogExtends(this.prefix.available, available);
      const prepared = prepareXaiBody(requestBody, {
        ...preparationOptions,
        ...(retainFrozen ? {
          definitionsOverride: this.prefix.definitions,
          retainFrozenDefinitions: true,
        } : {}),
      });
      let clean = prepared.clean;
      clean.instructions = [
        clean.instructions,
        routeIdentityInstructions(body, clean),
      ].filter(Boolean).join("\n\n");
      clean.prompt_cache_key = this.cacheKey;
      const compactedReplay = body.previous_response_id
        ? this.compactedContinuations.get(body.previous_response_id)
        : null;
      if (compactedReplay) clean.input = [...compactedReplay, ...(Array.isArray(clean.input) ? clean.input : [])];
      else if (body.previous_response_id) clean.previous_response_id = body.previous_response_id;
      const { bridge } = prepared;
      const finishStatus = publicStatus(emit);
      try {
        const compactedInput = compactedReplay
          ? { clean, compacted: false }
          : await compactLargeInput(clean, signal);
        clean = compactedInput.clean;
        let socket;
        try {
          socket = await this.connect(false);
        } catch (error) {
          if (error.code !== "XAI_AUTH_REJECTED") throw error;
          cachedToken = null;
          socket = await this.connect(true);
        }
        const warmupBytes = Buffer.byteLength(JSON.stringify({
          instructions: clean.instructions,
          tools: clean.tools,
          tool_choice: clean.tool_choice,
          parallel_tool_calls: clean.parallel_tool_calls,
        }));
        const shouldPrewarm = PREWARM_ENABLED
          && clean.generate !== false
          && !clean.previous_response_id
          && warmupBytes >= PREWARM_THRESHOLD_BYTES
          && Boolean(clean.instructions || (Array.isArray(clean.tools) && clean.tools.length));
        const reusePrefix = Boolean(clean.previous_response_id)
          && this.prefix
          && (this.prefix.catalogIdentity === prepared.catalogIdentity
            || catalogExtends(this.prefix.available, prepared.available))
          && this.prefix.instructions === (clean.instructions || "")
          && this.prefix.toolsJson === JSON.stringify(clean.tools || [])
          && this.prefix.effort === (clean.reasoning?.effort || null);
        let frame = { type: "response.create", ...clean };
        let providerPrewarmRequestBytes = 0;
        delete frame.stream;
        delete frame.background;
        if (reusePrefix) {
          delete frame.instructions;
          delete frame.tools;
        }
        if (shouldPrewarm) {
          const warmup = {
            type: "response.create",
            model: clean.model,
            store: false,
            generate: false,
            input: [],
            ...(clean.instructions ? { instructions: clean.instructions } : {}),
            ...(Array.isArray(clean.tools) ? { tools: clean.tools } : {}),
            ...(clean.tool_choice !== undefined ? { tool_choice: clean.tool_choice } : {}),
            ...(clean.parallel_tool_calls !== undefined
              ? { parallel_tool_calls: clean.parallel_tool_calls }
              : {}),
            prompt_cache_key: this.cacheKey,
          };
          const terminal = await this.exchange(socket, warmup, bridge, () => {}, signal);
          providerPrewarmRequestBytes = terminal.switchboard_request_bytes || 0;
          const warmupId = terminal?.response?.id;
          if (terminal?.type !== "response.completed" || !warmupId) {
            throw Object.assign(new Error("xAI prewarm did not complete"), { code: "XAI_PREWARM_FAILED" });
          }
          frame = { ...frame, previous_response_id: warmupId };
          delete frame.instructions;
          delete frame.tools;
        }
        const emitWithStatus = (event) => {
          if (event?.type === "response.created") return;
          if (terminalEvent(event)) finishStatus();
          emit(shiftOutputIndex(event));
        };
        const terminal = await this.exchange(socket, frame, bridge, emitWithStatus, signal);
        const providerResponseId = terminal?.response?.id;
        if (terminal?.type === "response.completed" && providerResponseId) {
          this.responseIds.delete(providerResponseId);
          this.responseIds.add(providerResponseId);
          while (this.responseIds.size > 64) this.responseIds.delete(this.responseIds.values().next().value);
          const output = Array.isArray(terminal.response?.output) && terminal.response.output.length
            ? terminal.response.output
            : terminal.switchboard_output_items || [];
          if ((compactedInput.compacted || compactedReplay) && output.length) {
            this.compactedContinuations.set(providerResponseId, [...clean.input, ...output]);
            while (this.compactedContinuations.size > 64) {
              this.compactedContinuations.delete(this.compactedContinuations.keys().next().value);
            }
          }
          const incomingDigests = xaiCallerDigests(body.input);
          const appendDelta = ownedContinuation
            && Array.isArray(this.priorCallerDigests)
            && this.priorCallerDigests.length > 0
            && !this.canContinue(body.input);
          this.priorCallerDigests = appendDelta
            ? [...this.priorCallerDigests, ...incomingDigests]
            : incomingDigests;
          this.prefix = {
            catalogIdentity: retainFrozen ? this.prefix.catalogIdentity : prepared.catalogIdentity,
            available: retainFrozen ? this.prefix.available : prepared.available,
            instructions: clean.instructions || "",
            toolsJson: JSON.stringify(clean.tools || []),
            effort: clean.reasoning?.effort || null,
            definitions: prepared.definitions,
          };
          this.lastUsedAt = Date.now();
          savePersistedXaiSession(this);
        }
        this.lastUsedAt = Date.now();
        return {
          status: 200,
          transport: "xai-ws",
          prewarmed: shouldPrewarm,
          compacted: compactedInput.compacted,
          compaction_scope: compactedInput.compaction_scope || null,
          tool_projection: {
            ...prepared.diagnostics,
            xai_prefix_reused: reusePrefix,
            provider_request_bytes: terminal.switchboard_request_bytes || 0,
            provider_prewarm_request_bytes: providerPrewarmRequestBytes,
            provider_input_bytes: Buffer.byteLength(JSON.stringify(clean.input || [])),
            provider_instruction_bytes: Buffer.byteLength(String(clean.instructions || "")),
            provider_tools_bytes: Buffer.byteLength(JSON.stringify(clean.tools || [])),
            provider_reasoning_effort: clean.reasoning?.effort || null,
          },
        };
      } catch (error) {
        finishStatus();
        throw error;
      }
    };
    const result = this.queue.then(operation, operation);
    this.queue = result.catch(() => {});
    return result;
  }

  close(deletePersisted = false) {
    this.socket?.close(1000, "session complete");
    this.socket = null;
    this.responseIds.clear();
    this.compactedContinuations.clear();
    this.priorCallerDigests = null;
    this.prefix = null;
    if (deletePersisted) removePersistedXaiSession(this.key);
  }
}

function sessionFor(key) {
  let session = sessions.get(key);
  if (!session) {
    session = new XaiSession(key);
    sessions.set(key, session);
  }
  return session;
}

function responseText(response) {
  if (typeof response?.output_text === "string" && response.output_text.trim()) return response.output_text.trim();
  return (Array.isArray(response?.output) ? response.output : [])
    .filter((item) => item?.type === "message")
    .flatMap((item) => Array.isArray(item.content) ? item.content : [])
    .map((part) => part?.text || part?.output_text || "")
    .filter(Boolean)
    .join("\n")
    .trim();
}

async function postXai(path, body, signal = null) {
  const fetchSignal = signal
    ? AbortSignal.any([signal, AbortSignal.timeout(REQUEST_TIMEOUT_MS)])
    : AbortSignal.timeout(REQUEST_TIMEOUT_MS);
  const bodyJson = JSON.stringify(body);
  const request = (bearer) => fetch(`${HTTP_BASE}${path}`, {
    method: "POST",
    headers: { authorization: `Bearer ${bearer}`, "content-type": "application/json" },
    body: bodyJson,
    signal: fetchSignal,
  });
  let bearer = await token(false);
  let response;
  try {
    response = await request(bearer);
  } catch (error) {
    if (signal?.aborted) throw cancelledError();
    if (error?.name === "AbortError" || error?.name === "TimeoutError") {
      throw Object.assign(new Error(`xAI ${path} timed out`), { code: "XAI_TIMEOUT" });
    }
    throw error;
  }
  if (response.status === 401) {
    cachedToken = null;
    bearer = await token(true);
    try {
      response = await request(bearer);
    } catch (error) {
      if (signal?.aborted) throw cancelledError();
      if (error?.name === "AbortError" || error?.name === "TimeoutError") {
        throw Object.assign(new Error(`xAI ${path} timed out`), { code: "XAI_TIMEOUT" });
      }
      throw error;
    }
  }
  const text = await response.text();
  let parsed;
  try { parsed = JSON.parse(text); } catch { parsed = null; }
  if (!response.ok || !parsed) {
    throw rejectedRequestError(path, response.status, text, bodyJson, body);
  }
  return parsed;
}

async function compact(body) {
  const { clean } = prepareXaiBody({ ...body, tools: [] }, {
    allowProviderContinuation: false,
    retainHistoryAuthority: true,
  });
  // The provider checkpoint (for Grok's own continuation) and the portable
  // summary (for every other route) read the same input, so they run together.
  const [compacted, summaryResponse] = await Promise.all([
    postXai("/responses/compact", {
      model: clean.model,
      input: clean.input || [],
    }),
    postXai("/responses", {
      model: clean.model,
      store: false,
      stream: false,
      tools: [],
      instructions: [
        "Create a canonical, provider-neutral context summary for another coding model.",
        "Preserve user requirements, decisions, file paths, code state, tool results, blockers, and pending work.",
        "Return only the summary. Do not use tools and do not include private reasoning.",
      ].join(" "),
      input: clean.input || [],
    }),
  ]);
  const summary = responseText(summaryResponse);
  if (!summary) throw Object.assign(new Error("xAI returned an empty canonical summary"), { code: "XAI_COMPACT_EMPTY" });
  return {
    provider_item: Array.isArray(compacted.output) ? compacted.output[0] : null,
    summary,
    usage: compacted.usage || summaryResponse.usage || {},
  };
}

function send(message) {
  if (process.send) process.send(message);
}

const activeSessions = new Map();
const activeWork = new Set();
let terminating = false;

function registerSession(sessionKey, controller) {
  const controllers = activeSessions.get(sessionKey) || new Set();
  controllers.add(controller);
  activeSessions.set(sessionKey, controllers);
}

function unregisterSession(sessionKey, controller) {
  const controllers = activeSessions.get(sessionKey);
  if (!controllers) return;
  controllers.delete(controller);
  if (controllers.size === 0) activeSessions.delete(sessionKey);
}

process.on("message", (job) => {
  if (!job || typeof job.id !== "string") return;
  if (job.op === "close_session") {
    for (const controller of activeSessions.get(job.session_key) || []) controller.abort();
    const existing = sessions.get(job.session_key);
    if (existing) {
      existing.close(true);
      sessions.delete(job.session_key);
    } else {
      removePersistedXaiSession(job.session_key);
    }
    send({ id: job.id, kind: "done", result: { status: 200 } });
    return;
  }
  if (job.op === "crash" && process.env.SWITCHBOARD_TEST_ALLOW_CRASH === "1") process.exit(86);
  const sessionKey = job.session_key || job.id;
  // Closing an owner (a connection or request) cancels its jobs only; closing
  // the session key also closes the thread session itself.
  const ownerKey = job.owner_key || sessionKey;
  const controller = new AbortController();
  registerSession(sessionKey, controller);
  if (ownerKey !== sessionKey) registerSession(ownerKey, controller);
  const work = job.op === "compact"
    ? compact(job.body)
    : sessionFor(sessionKey).run(job.body, (event) => {
        send({ id: job.id, kind: "event", event });
      }, controller.signal);
  const completion = Promise.resolve(work).then(
    (result) => send({ id: job.id, kind: "done", result }),
    (error) => {
      const cancelled = controller.signal.aborted || error.name === "AbortError" || error.code === "XAI_REQUEST_CANCELLED";
      send({
        id: job.id,
        kind: "error",
        error: cancelled
          ? safeWorkerError("XAI_REQUEST_CANCELLED", "xAI request was cancelled when the downstream session closed.", 499)
          : safeWorkerError(error.code || "XAI_WORKER_ERROR", error.message || "xAI worker failed", error.status || 502),
      });
    },
  ).finally(() => {
    unregisterSession(sessionKey, controller);
    unregisterSession(ownerKey, controller);
  });
  activeWork.add(completion);
  completion.then(
    () => activeWork.delete(completion),
    () => activeWork.delete(completion),
  );
});

setInterval(() => {
  const cutoff = Date.now() - IDLE_SESSION_MS;
  for (const [key, session] of sessions) {
    if (session.lastUsedAt < cutoff) {
      session.close(false);
      sessions.delete(key);
    }
  }
}, 60_000).unref();

process.on("SIGTERM", () => {
  if (terminating) return;
  terminating = true;
  for (const controllers of activeSessions.values()) {
    for (const controller of controllers) controller.abort();
  }
  for (const session of sessions.values()) session.close(false);
  const guard = setTimeout(() => process.exit(1), 5_000);
  guard.unref?.();
  Promise.allSettled([...activeWork]).then(() => {
    clearTimeout(guard);
    process.exit(0);
  });
});
